def resource_paths(package_dir: Path, resource: Dict[str, Any]) -> List[Path]:
    p = resource.get("path")
    if p is None:
        raise ValueError(f"Resource {resource.get('name', '<unnamed>')} has no 'path'")
    if isinstance(p, str):
        p_list = [p]
    elif isinstance(p, list):
        p_list = p
    else:
        raise TypeError("'path' must be string or list of strings")
    paths: List[Path] = []
    for rel in p_list:
        candidate = (package_dir / rel).resolve()
        # prevent escaping the package dir
        if not str(candidate).startswith(str(package_dir.resolve())):
            raise ValueError(f"Unsafe path for resource {resource.get('name')}: {rel}")
        paths.append(candidate)
    return paths


def csv_reader_for_resource(
    fp, resource: Dict[str, Any], *, force_schema_headers: bool = False
):
    dialect = resource.get("dialect", {}) or {}
    delimiter = dialect.get("delimiter", ";")
    quotechar = dialect.get("quoteChar") or dialect.get("quotechar") or '"'
    doublequote = dialect.get("doubleQuote") if "doubleQuote" in dialect else True
    escapechar = dialect.get("escapeChar") or None

    # If schema defines fields and we force schema headers, use them
    fieldnames = None
    if force_schema_headers:
        schema = resource.get("schema") or {}
        if isinstance(schema, dict):
            fields = schema.get("fields") or []
            if fields and all(isinstance(f, dict) and "name" in f for f in fields):
                fieldnames = [f["name"] for f in fields]

    if fieldnames is not None:
        return csv.DictReader(
            fp,
            delimiter=delimiter,
            quotechar=quotechar,
            doublequote=doublequote,
            escapechar=escapechar,
            fieldnames=fieldnames,
        )
    else:
        return csv.DictReader(
            fp,
            delimiter=delimiter,
            quotechar=quotechar,
            doublequote=doublequote,
            escapechar=escapechar,
        )


